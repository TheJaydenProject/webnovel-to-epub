// Serve the project and open tests/gallery.html. No remote requests.
import { validateGalleryUrl, canonicalDreamyNovelUrl, normalizeBookTitle, parseDreamyGallery, parseDreamyNovel, gallerySkipReason, scanEpubLibrary } from "../core/Gallery.js";
import { EpubCompiler } from "../core/EpubCompiler.js?gallery-test";
import { readDreamyPage } from "../core/DreamyPage.js";
const result = document.getElementById("result");
let checks = 0;
function assert(condition, message) { if (!condition) throw new Error(message); checks++; }
function throws(fn, message) { let threw = false; try { fn(); } catch { threw = true; } assert(threw, message); }
const base = "https://dreamy-translations.com";
const url = base + "/novel/test";
const parse = html => new DOMParser().parseFromString(html, "text/html");
const novelHtml = (premium = "<button>Premium (0)</button>") => `<h1>Test Book</h1><button>Free (2)</button>${premium}<a data-chapter-index="1" href="/novel/test/chapter/1">One</a><a data-chapter-index="0" href="/novel/test/chapter/0">Prologue</a>`;
try {
  assert(validateGalleryUrl(base + "/series/") === base + "/series", "Gallery canonical URL");
  for (const bad of [base + "/series?q=x", "https://evil.example/series", "file:///series", "https://user:secret@dreamy-translations.com/series"]) throws(() => validateGalleryUrl(bad), "Reject invalid gallery");
  assert(canonicalDreamyNovelUrl(url + "/?x=1#top") === url, "Canonical novel URL");
  assert(canonicalDreamyNovelUrl(url + "/chapter/0") === null, "Not a novel index");
  assert(normalizeBookTitle("Ｔest: Book (Hiatus)") === "testbook", "Unicode and punctuation normalization");
  const cards = `<a href="/novel/test"><h3>Test Book</h3></a><a href="/novel/test"><h3>Test Book</h3></a><a href="/novel/test/chapter/0">Not a card</a>`;
  assert(parseDreamyGallery(parse(cards), base).length === 1, "Deduplicate cards");
  throws(() => parseDreamyGallery(parse("<p>Loading</p>"), base), "Empty gallery fails");
  throws(() => parseDreamyGallery(parse('<a href="https://evil.example/novel/test"><h3>Bad</h3></a>'), base), "Untrusted card fails");
  const novel = { tocUrl: url, ...parseDreamyNovel(parse(novelHtml()), url) };
  assert(novel.premium === 0 && novel.free === 2 && novel.chapterCount === 2, "Explicit counts");
  assert(novel.firstChapterUrl.endsWith("/0"), "Include prologue in numeric order");
  assert(parseDreamyNovel(parse(novelHtml("")), url).premium === null, "Missing badge is unknown");
  assert(parseDreamyNovel(parse(novelHtml("<button>Premium (0)</button><button>Premium (20)</button>")), url).premium === null, "Contradictory counts unknown");
  throws(() => parseDreamyNovel(parse(novelHtml().replace('/novel/test/chapter/1', 'https://evil.example/chapter/1')), url), "Untrusted chapter fails");
  const compiler = new EpubCompiler({ title: "Test Book", author: "Author", sourceUrl: url });
  compiler.addChapter("One", "<p>Hello</p>");
  const good = new File([await compiler.generate()], "Custom filename.epub");
  Object.defineProperty(good, "webkitRelativePath", { value: "Library/Nested/Custom filename.epub" });
  const corrupt = new File(["broken"], "Another Book (1).EPUB");
  const library = await scanEpubLibrary([good, corrupt, new File(["ignore"], "readme.txt")]);
  assert(library.count === 2 && library.warnings.length === 1, "Corrupt fallback, ignore non-EPUB");
  assert(library.titles.has("testbook") && library.titles.has("customfilename") && library.titles.has("anotherbook"), "Metadata, filename, browser suffix matching");
  assert(library.sources.get(url) === good.webkitRelativePath, `Persist source metadata and relative folder path: ${JSON.stringify([...library.sources])} / ${good.webkitRelativePath}`);
  const options = { skipHiatus: true, onlyFree: true };
  const empty = { titles: new Map(), sources: new Map() };
  assert(gallerySkipReason(novel, library, new Set(), options).status === "existing", "Skip existing EPUB");
  assert(gallerySkipReason({ ...novel, title: "Renamed" }, library, new Set(), options).status === "existing", "Source match survives title rename");
  assert(gallerySkipReason({ ...novel, tocUrl: url + "2" }, library, new Set(), options).status === "existing", "Title match older EPUBs");
  assert(gallerySkipReason(novel, empty, new Set([url]), options).status === "queued", "Skip queued");
  assert(gallerySkipReason({ ...novel, title: "Test (HIATUS)" }, empty, new Set(), options).status === "hiatus", "Hiatus case insensitive");
  assert(gallerySkipReason({ ...novel, premium: 20 }, empty, new Set(), options).status === "premium", "Skip premium");
  assert(gallerySkipReason({ ...novel, premium: null }, empty, new Set(), options).status === "unknown", "Fail closed unknown");
  assert(gallerySkipReason(novel, empty, new Set(), options) === null, "Explicit free eligible");
  assert(gallerySkipReason(novel, empty, new Set(), { ...options, onlyCompleted: true }).status === "notCompleted", "Unknown completion excluded");
  assert(gallerySkipReason({ ...novel, completed: false }, empty, new Set(), { ...options, onlyCompleted: true }).status === "notCompleted", "Ongoing excluded even with zero premium");
  assert(gallerySkipReason({ ...novel, completed: true }, empty, new Set(), { ...options, onlyCompleted: true }) === null, "Verified completed eligible");
  throws(() => parseDreamyGallery(parse(cards), base, true), "Unverified completed filter fails closed");
  assert(gallerySkipReason({ ...novel, title: "Book (Hiatus)", premium: 20 }, empty, new Set(), { skipHiatus: false, onlyFree: false }) === null, "Filters can be disabled");
  assert(gallerySkipReason({ ...novel, tocUrl: url + "2", title: "Test Book Sequel" }, library, new Set(), options) === null, "No fuzzy substring matching");
  assert((await scanEpubLibrary([good], { cancelled: () => true })).count === 0, "Cancel local scan");
  const zip = await JSZip.loadAsync(await good.arrayBuffer());
  zip.file("OEBPS/content.opf", "x".repeat(2 * 1024 * 1024 + 1));
  const oversized = await scanEpubLibrary([new File([await zip.generateAsync({ type: "blob", compression: "DEFLATE" })], "Large.epub")]);
  assert(oversized.warnings[0].includes("2 MB"), "Bound decompressed metadata");
  zip.file("OEBPS/content.opf", '<!DOCTYPE package><package/>');
  assert((await scanEpubLibrary([new File([await zip.generateAsync({ type: "blob" })], "Bad XML.epub")])).warnings[0].includes("XML declarations"), "Reject declarations");
  const originalUrl = location.href;
  history.replaceState(null, "", "/novel/test");
  const fixture = document.createElement("section");
  fixture.innerHTML = novelHtml();
  document.body.append(fixture);
  assert((await readDreamyPage()).includes("Prologue"), "Rendered novel readiness");
  fixture.remove();
  history.replaceState(null, "", "/series");
  const completedFixture = document.createElement("section");
  completedFixture.innerHTML = cards + '<a id="ongoing" href="/novel/ongoing"><h3>Ongoing</h3></a><button>Completed</button>';
  document.body.append(completedFixture);
  const completedButton = completedFixture.querySelector("button");
  completedButton.addEventListener("click", () => setTimeout(() => {
    completedButton.style.backgroundColor = "rgb(245, 158, 11)";
    completedFixture.querySelector("#ongoing").remove();
  }, 50));
  const completedDoc = parse(await readDreamyPage(true));
  assert(parseDreamyGallery(completedDoc, base, true).length === 1, "Native completed filter waits for updated cards");
  completedFixture.remove();
  history.replaceState(null, "", originalUrl);
  result.textContent = `PASS: ${checks} gallery checks`;
} catch (err) { result.textContent = `FAIL: ${err.stack}`; throw err; }
